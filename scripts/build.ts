import { mkdir, copyFile, cp, chmod, readdir, rm } from "node:fs/promises";
import { join } from "node:path";
import { RELEASE_VERSION } from "@cross-harness-comms/protocol";

const root = join(import.meta.dir, "..");
const UNIX_TARGETS = ["bun-darwin-arm64", "bun-darwin-x64", "bun-linux-arm64", "bun-linux-x64"];
type ReleaseTarget = "darwin-arm64" | "darwin-x64" | "linux-arm64" | "linux-x64";
const RELEASE_TARGETS: ReleaseTarget[] = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"];
// `compareVersions` ignores pre-release suffixes, and a version names a directory, so only plain versions are built.
const PLAIN_VERSION = /^\d+\.\d+\.\d+$/;
const CODEX_MARKETPLACE_ENTRY = { policy: { installation: "AVAILABLE", authentication: "ON_INSTALL" }, category: "Productivity" };

// The `uname -s` and `uname -m` pairs each release target runs on.
const UNAME: Record<ReleaseTarget, string> = {
  "darwin-arm64": '"Darwin arm64"', "darwin-x64": '"Darwin x86_64"', "linux-arm64": '"Linux aarch64" | "Linux arm64"', "linux-x64": '"Linux x86_64"',
};

// The released plugins' `bin/comms`: downloads the pinned core from the GitHub release on first use, checks its SHA-256, and
// execs it. It never writes to stdout and nothing before `exec` reads stdin, since hooks and the MCP server speak JSON there.
export function launcherScript(version: string, checksums: Readonly<Record<ReleaseTarget, string>>): string {
  if (!PLAIN_VERSION.test(version)) throw new Error(`Release version must be plain MAJOR.MINOR.PATCH: ${JSON.stringify(version)}`);
  for (const target of RELEASE_TARGETS) {
    if (!/^[0-9a-f]{64}$/.test(checksums[target] ?? "")) throw new Error(`Malformed SHA-256 checksum for ${target}`);
  }
  const cases = RELEASE_TARGETS.map(target => `  ${UNAME[target]}) target=${target} checksum=${checksums[target]} ;;\n`).join("");
  return `#!/bin/sh
# Generated by scripts/build.ts. Runs the comms core ${version}, downloading it from the GitHub release on first use.
set -eu
umask 077
version=${version}
os=$(uname -s </dev/null)
arch=$(uname -m </dev/null)
case "$os $arch" in
${cases}  *) echo "comms: unsupported platform $os $arch" >&2; exit 1 ;;
esac
directory="\${COMMS_DATA_DIR:-$HOME/.local/share/comms}/releases/$version"
binary="$directory/comms"
if [ -x "$binary" ]; then exec "$binary" "$@"; fi
url="\${COMMS_RELEASE_URL:-https://github.com/esmoradian/cross-harness-comms/releases/download/v$version}/comms-$target"
if ! command -v curl >/dev/null 2>&1 </dev/null; then echo "comms: curl is required to download the comms core" >&2; exit 1; fi
if command -v shasum >/dev/null 2>&1 </dev/null; then sha="shasum -a 256"
elif command -v sha256sum >/dev/null 2>&1 </dev/null; then sha=sha256sum
else echo "comms: shasum or sha256sum is required to verify the comms core" >&2; exit 1
fi
mkdir -p "$directory" </dev/null
# Named by this shell's PID and renamed into place, so concurrent first runs never see a partial core.
temporary="$directory/comms.$$"
trap 'rm -f "$temporary"' EXIT
trap 'exit 1' HUP INT TERM
if ! curl -fsSL --retry 2 --connect-timeout 10 -o "$temporary" "$url" </dev/null 2>/dev/null; then
  echo "comms: could not download the comms core $version from $url" >&2; exit 1
fi
actual=$($sha "$temporary" </dev/null 2>/dev/null) || actual=
if [ "\${actual%% *}" != "$checksum" ]; then echo "comms: checksum mismatch for $url" >&2; exit 1; fi
chmod 700 "$temporary" </dev/null
mv -f "$temporary" "$binary" </dev/null
trap - EXIT HUP INT TERM
exec "$binary" "$@"
`;
}

// Copies a plugin manifest directory and stamps the release version after `name`, so no manifest carries its own copy.
async function copyManifest(source: string, output: string): Promise<void> {
  await cp(source, output, { recursive: true });
  const { name, ...rest } = await Bun.file(`${source}/plugin.json`).json();
  await Bun.write(`${output}/plugin.json`, JSON.stringify({ name, version: RELEASE_VERSION, ...rest }, null, 2) + "\n");
}

// Bundles the Pi extension into `outdir` as `index.js`.
export async function buildPiExtension(outdir: string): Promise<void> {
  // Pi provides pi-tui to extensions at runtime, so the card uses that copy.
  const build = await Bun.build({ entrypoints: [join(root, "adapters/pi/src/index.ts")], outdir, target: "node", format: "esm",
    external: ["@earendil-works/pi-tui"] });
  if (!build.success) throw new AggregateError(build.logs, "Pi build failed");
}

// Writes the three plugins and both marketplaces under `outdir`, with `writeBinary` producing each `bin/comms`.
async function writePlugins(outdir: string, marketplace: string, writeBinary: (path: string) => Promise<void>): Promise<void> {
  for (const harness of ["pi", "claude", "codex"]) {
    const output = join(outdir, "plugins", harness);
    await mkdir(`${output}/bin`, { recursive: true });
    await writeBinary(`${output}/bin/comms`);
    await chmod(`${output}/bin/comms`, 0o755);
    if (harness === "pi") {
      await buildPiExtension(`${output}/src`);
      await Bun.write(`${output}/package.json`, JSON.stringify({ name: "@cross-harness-comms/pi", version: RELEASE_VERSION, type: "module",
        pi: { extensions: ["./src/index.js"] } }, null, 2) + "\n");
    } else if (harness === "claude") {
      await copyManifest(join(root, "adapters/claude/.claude-plugin"), `${output}/.claude-plugin`);
      await cp(join(root, "adapters/claude/hooks"), `${output}/hooks`, { recursive: true });
      const build = await Bun.build({ entrypoints: [join(root, "adapters/claude/src/index.ts")], outdir: `${output}/hooks`, naming: "register.js",
        target: "browser", format: "esm" });
      if (!build.success) throw new AggregateError(build.logs, "Claude build failed");
    } else {
      await copyManifest(join(root, "adapters/codex/.codex-plugin"), `${output}/.codex-plugin`);
      await cp(join(root, "adapters/codex/hooks"), `${output}/hooks`, { recursive: true });
      await copyFile(join(root, "adapters/codex/.mcp.json"), `${output}/.mcp.json`);
    }
  }
  await mkdir(join(outdir, ".agents/plugins"), { recursive: true });
  await Bun.write(join(outdir, ".agents/plugins/marketplace.json"), JSON.stringify({ name: marketplace, plugins: [{ name: "cross-harness-comms",
    source: { source: "local", path: "./plugins/codex" }, ...CODEX_MARKETPLACE_ENTRY }] }, null, 2) + "\n");
  await mkdir(join(outdir, ".claude-plugin"), { recursive: true });
  await Bun.write(join(outdir, ".claude-plugin/marketplace.json"), JSON.stringify({ name: marketplace, owner: { name: "esmoradian" },
    plugins: [{ name: "cross-harness-comms", source: "./plugins/claude" }] }, null, 2) + "\n");
}

// Writes the `release` branch tree: the plugins with the launcher as each `bin/comms`, marketplaces named `comms`, and a root
// package.json for a Git Pi install. It compiles nothing.
export async function writeReleaseTree(outdir: string, checksums: Readonly<Record<ReleaseTarget, string>>): Promise<void> {
  const launcher = launcherScript(RELEASE_VERSION, checksums);
  await mkdir(outdir, { recursive: true });
  if ((await readdir(outdir)).length) throw new Error(`Release tree output ${outdir} is not empty`);
  await writePlugins(outdir, "comms", path => Bun.write(path, launcher).then(() => {}));
  await Bun.write(join(outdir, "package.json"), JSON.stringify({ name: "cross-harness-comms", version: RELEASE_VERSION, private: true, type: "module",
    pi: { extensions: ["./plugins/pi/src/index.js"] } }, null, 2) + "\n");
}

async function compile(target: string, outfile: string): Promise<void> {
  // The target is chosen at build time. No runtime operating system selection.
  const build = Bun.spawn([process.execPath, "build", "--compile", `--target=${target}`, "packages/core/src/main.unix.ts", "--outfile", outfile],
    { cwd: root, stdout: "inherit", stderr: "inherit" });
  if (await build.exited) throw new Error(`Core build failed for ${target}`);
  // Bun appends the bundle after linking, which invalidates the linker's ad-hoc signature, so macOS cores are signed again.
  if (target.startsWith("bun-darwin-")) {
    const sign = Bun.spawn(["codesign", "--force", "--sign", "-", outfile], { stdout: "inherit", stderr: "inherit" });
    if (await sign.exited) throw new Error(`Signing the ${target} core failed; macOS cores must be built on macOS`);
  }
}

async function release(): Promise<void> {
  const output = join(root, "dist/release");
  await rm(output, { recursive: true, force: true });
  const checksums = {} as Record<ReleaseTarget, string>;
  for (const target of RELEASE_TARGETS) {
    const asset = join(output, "assets", `comms-${target}`);
    await compile(`bun-${target}`, asset);
    checksums[target] = new Bun.CryptoHasher("sha256").update(await Bun.file(asset).arrayBuffer()).digest("hex");
  }
  await Bun.write(join(output, "assets/SHA256SUMS"), RELEASE_TARGETS.map(target => `${checksums[target]}  comms-${target}\n`).join(""));
  await writeReleaseTree(join(output, "tree"), checksums);
  console.log(`Built the ${RELEASE_VERSION} release assets and tree in dist/release/`);
}

async function main() {
  if (!PLAIN_VERSION.test(RELEASE_VERSION)) throw new Error(`RELEASE_VERSION must be plain MAJOR.MINOR.PATCH: ${RELEASE_VERSION}`);
  if (process.argv[2] === "release") return await release();
  const target = process.argv[2] ?? "bun-darwin-arm64";
  if (!UNIX_TARGETS.includes(target)) throw new Error("Unsupported Unix target");
  const dist = join(root, "dist");
  // Rebuilt from scratch so files no longer produced stop shipping.
  await rm(join(dist, "plugins"), { recursive: true, force: true });
  await compile(target, join(dist, "comms"));
  await writePlugins(dist, "comms-local", path => copyFile(join(dist, "comms"), path));
  console.log(`Built core and local harness packages for ${target} in dist/`);
}

if (import.meta.main) await main();
